namespace Lumina.Domain.SharedKernel.Common.Enums.Scheduling;

/// <summary>
/// Enumeration for the units in which the display time span of the scheduler page is expressed.
/// </summary>
public enum SchedulerDisplayTimeUnit
{
    /// <summary>
    /// The display time span is expressed in minutes.
    /// </summary>
    Minutes,

    /// <summary>
    /// The display time span is expressed in hours.
    /// </summary>
    Hours,

    /// <summary>
    /// The display time span is expressed in days.
    /// </summary>
    Days
}
