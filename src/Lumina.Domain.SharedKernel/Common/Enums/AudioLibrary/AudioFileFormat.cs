namespace Lumina.Domain.SharedKernel.Common.Enums.AudioLibrary;

/// <summary>
/// Enumeration for the file formats of audio files.
/// </summary>
public enum AudioFileFormat
{
    /// <summary>
    /// No audio file format specified.
    /// </summary>
    None,

    /// <summary>
    /// MPEG-1 Audio Layer III.
    /// </summary>
    MP3,

    /// <summary>
    /// Free Lossless Audio Codec.
    /// </summary>
    FLAC,

    /// <summary>
    /// MPEG-4 Part 14 audio.
    /// </summary>
    M4A,

    /// <summary>
    /// Advanced Audio Coding.
    /// </summary>
    AAC,

    /// <summary>
    /// The Ogg container format.
    /// </summary>
    OGG,

    /// <summary>
    /// Opus.
    /// </summary>
    OPUS,

    /// <summary>
    /// Waveform Audio File Format.
    /// </summary>
    WAV,

    /// <summary>
    /// Windows Media Audio.
    /// </summary>
    WMA,

    /// <summary>
    /// Audio Interchange File Format.
    /// </summary>
    AIFF,

    /// <summary>
    /// Monkey's Audio.
    /// </summary>
    APE,

    /// <summary>
    /// WavPack.
    /// </summary>
    WAVPACK,

    /// <summary>
    /// Direct Stream Digital.
    /// </summary>
    DSF,

    /// <summary>
    /// Direct Stream Digital Interchange File Format.
    /// </summary>
    DFF,

    /// <summary>
    /// Matroska audio.
    /// </summary>
    MATROSKA,
}
